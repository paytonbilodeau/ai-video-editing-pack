// Generate Direction C's sfx-timeline.json from the physics bakes.
//
// SFX SYNC LAW: every cue time must be DERIVED from the scene, never
// estimated. A bake already knows the exact frame of every impact, so this
// script reads the SAME specs the component renders (src/videos/bench0808/
// specs.ts) and emits cues straight from the simulation. Nothing is
// hand-timed, and re-tuning a spec regenerates the timeline instead of
// silently drifting away from it.
//
// Usage (from flow/):
//   npx tsc src/lib/lanes.ts src/lib/physics.ts src/videos/bench0808/specs.ts \
//     --outDir /tmp/flowcheck --module commonjs --target ES2022 \
//     --moduleResolution node --esModuleInterop --skipLibCheck --strict
//   NODE_PATH="$PWD/node_modules" node scripts/bench-sfx.mjs /tmp/flowcheck \
//     src/videos/bench0808/sfx-timeline.json

import {createRequire} from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const outDir = process.argv[2] ?? '/tmp/flowcheck';
const target = process.argv[3] ?? 'src/videos/bench0808/sfx-timeline.json';
const require = createRequire(import.meta.url);

const load = (...cands) => {
  for (const c of cands) {
    try {
      return require(path.resolve(outDir, c));
    } catch (e) {
      if (e.code !== 'MODULE_NOT_FOUND') throw e;
    }
  }
  throw new Error(`cannot resolve any of ${cands.join(', ')} under ${outDir}`);
};

const physics = load('physics.js', 'lib/physics.js');
const specs = load('specs.js', 'videos/bench0808/specs.js');

const events = [];
const summary = [];

for (const src of specs.SFX_SOURCES) {
  physics.clearBakeCache();
  const b = physics.bake({
    spec: src.spec,
    seed: src.seed,
    fps: specs.FPS,
    durationInFrames: specs.dur(src.phase),
  });

  // Pours are many small impacts: keep them sparse and quiet (ticks).
  // A stack or a scale is a few decisive landings: allow the heavier cue.
  const isPour = src.spec.kind === 'pour';
  const cues = physics.collisionsToSfx(b, src.phase.in, {
    soft: isPour ? 'tick' : 'pop',
    hard: isPour ? 'pop' : 'thump',
    hardAbove: isPour ? 5.5 : 3.5,
    minGap: isPour ? 0.16 : 0.1,
    max: isPour ? 14 : 10,
  });

  events.push(...cues);
  summary.push({
    phase: src.name,
    seed: src.seed,
    checksum: physics.bakeChecksum(b),
    collisions: b.collisions.length,
    settledFrame: b.settledFrame,
    cues: cues.length,
  });
}

events.sort((a, b) => a.t - b.t);

const doc = {
  _comment:
    'GENERATED by scripts/bench-sfx.mjs from the matter-js bakes in ' +
    'src/videos/bench0808/specs.ts. Do not hand-edit: re-run the script ' +
    'after any spec change so cue times stay derived from the simulation.',
  video: 'bench0808 direction C (physical metaphor)',
  segment: {start: 20.4, end: 42.5, durationSeconds: 22.1, fps: specs.FPS},
  bakes: summary,
  events,
};

fs.mkdirSync(path.dirname(target), {recursive: true});
fs.writeFileSync(target, `${JSON.stringify(doc, null, 2)}\n`);

console.log(`wrote ${target}`);
console.log(`  ${events.length} cues from ${summary.length} bakes`);
for (const s of summary) {
  console.log(
    `  ${s.phase.padEnd(10)} checksum=${s.checksum} collisions=${String(
      s.collisions
    ).padStart(3)} cues=${String(s.cues).padStart(2)} settled@${s.settledFrame}`
  );
}
